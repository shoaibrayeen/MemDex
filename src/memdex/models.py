class AuditEvent:
    id: str
    event: str
    at: str
    summary: str = ""
    tokens_before: int = 0
    tokens_after: int = 0
    tokens_saved: int = 0
    pct_saved: float = 0.0
    files_written: int = 0
    units: int = 0
    vectors: int = 0
    mode_label: str = ""
