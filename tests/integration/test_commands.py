class TestRestore:
    def test_round_trip_restores_the_original_bytes(self, runner, demo_project: Path):
        before = tree_hash(demo_project, "MEMORY.md", "memory")
        run(runner, "run")
        assert tree_hash(demo_project, "MEMORY.md", "memory") != before

        run(runner, "restore", "--latest", "--yes")
        assert tree_hash(demo_project, "MEMORY.md", "memory") == before

    def test_removes_files_memdex_created(self, runner, demo_project: Path):
        run(runner, "run")
        assert list(demo_project.glob("memory/*/*.md"))
        run(runner, "restore", "--latest", "--yes")
        assert not list(demo_project.glob("memory/*/*.md"))

    def test_takes_its_own_backup_first(self, runner, demo_project: Path):
        run(runner, "run")
        run(runner, "restore", "--latest", "--yes")
        reasons = [
            json.loads((d / "manifest.json").read_text(encoding="utf-8"))["reason"]
            for d in (demo_project / ".memdex" / "backups").iterdir()
        ]
        assert any(r.startswith("pre-restore") for r in reasons)

    def test_restore_is_recorded(self, runner, demo_project: Path):
        run(runner, "run")
        run(runner, "restore", "--latest", "--yes")
        assert "restore" in run(runner, "history").output

    def test_without_backups_it_says_so(self, runner, demo_project: Path):
        result = runner.invoke(app, ["restore", "--latest"])
        assert result.exit_code == 1
        assert "no backups" in result.output.lower()


class TestClean:
    def test_clears_the_index_but_keeps_the_files(self, runner, demo_project: Path):
        run(runner, "run")
        tree = tree_hash(demo_project, "MEMORY.md", "memory")

        result = run(runner, "clean", "--yes")

        assert "Cleared" in result.output
        assert tree_hash(demo_project, "MEMORY.md", "memory") == tree
        assert not (demo_project / ".memdex" / "metadata" / "memories.json").exists()
        assert (demo_project / ".memdex" / "config.yaml").exists()

    def test_keeps_backups(self, runner, demo_project: Path):
        run(runner, "run")
        backups = len(list((demo_project / ".memdex" / "backups").iterdir()))
        run(runner, "clean", "--yes")
        assert len(list((demo_project / ".memdex" / "backups").iterdir())) == backups

    def test_records_that_the_user_cleaned(self, runner, demo_project: Path):
        run(runner, "run")
        run(runner, "clean", "--yes")
        output = run(runner, "history").output
        assert "clean" in output
        assert "memory data was reset, log kept" in output

    def test_a_later_run_rebuilds(self, runner, demo_project: Path):
        run(runner, "run")
        run(runner, "clean", "--yes")
        run(runner, "run")
        assert "Chroma selection" in run(runner, "search", "chroma decision").output

    def test_all_requires_confirmation(self, runner, demo_project: Path):
        run(runner, "run")
        result = runner.invoke(app, ["clean", "--all"])
        assert result.exit_code == 1
        assert (demo_project / ".memdex").exists()

    def test_all_removes_everything_but_the_memory_files(self, runner, demo_project: Path):
        run(runner, "run")
        tree = tree_hash(demo_project, "MEMORY.md", "memory")
        run(runner, "clean", "--all", "--yes")
        assert not (demo_project / ".memdex").exists()
        assert tree_hash(demo_project, "MEMORY.md", "memory") == tree
