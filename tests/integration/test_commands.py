from __future__ import annotations

import json
from pathlib import Path

from memdex.cli import app
from tests.conftest import tree_hash, write_config


def run(runner, *args, **kwargs):
    result = runner.invoke(app, list(args), **kwargs)
    assert result.exit_code == 0, result.output
    return result


class TestDryRun:
    def test_writes_nothing_at_all(self, runner, demo_project: Path):
        before = tree_hash(demo_project, "MEMORY.md", "memory", ".claude")
        result = run(runner, "run", "--dry-run")
        assert tree_hash(demo_project, "MEMORY.md", "memory", ".claude") == before
        assert "Nothing was written" in result.output

    def test_shows_the_proposed_changes_and_metrics(self, runner, demo_project: Path):
        result = run(runner, "run", "--dry-run")
        assert "Proposed changes" in result.output
        assert "write" in result.output and "memory/" in result.output
        assert "Before:" in result.output

    def test_never_creates_the_vector_store(self, runner, demo_project: Path):
        run(runner, "run", "--dry-run")
        chroma = demo_project / ".memdex" / "chroma"
        assert not chroma.exists() or not any(chroma.iterdir())

    def test_records_no_activity(self, runner, demo_project: Path):
        run(runner, "run", "--dry-run")
        result = run(runner, "history")
        assert "No activity recorded yet" in result.output

    def test_compact_dry_run_ends_with_the_apply_hint(self, runner, demo_project: Path):
        run(runner, "run")
        result = run(runner, "compact", "--dry-run")
        assert "Memory Analysis" in result.output
        assert "Run without --dry-run to apply." in result.output


