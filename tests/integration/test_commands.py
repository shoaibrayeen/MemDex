class TestIndexCommand:
    def test_regenerates_only_the_index(self, runner, demo_project: Path):
        run(runner, "run")
        tree_before = tree_hash(demo_project, "memory")
        (demo_project / "MEMORY.md").write_text("<!-- generated by memdex -->\nstale\n", "utf-8")

        run(runner, "index")

        assert tree_hash(demo_project, "memory") == tree_before
        assert "# Memory Index" in (demo_project / "MEMORY.md").read_text(encoding="utf-8")

    def test_refuses_to_overwrite_unmigrated_notes(self, runner, demo_project: Path):
        result = runner.invoke(app, ["index"])
        assert result.exit_code == 1
        assert "memdex run" in result.output
        assert "# Project Memory" in (demo_project / "MEMORY.md").read_text(encoding="utf-8")

    def test_reembeds_an_edited_memory(self, runner, demo_project: Path):
        run(runner, "run")
        target = next(demo_project.glob("memory/*/database*.md"))
        target.write_text(
            target.read_text(encoding="utf-8")
            + "\nWe also run a read replica in Frankfurt.\n",
            encoding="utf-8",
        )
        result = run(runner, "index")
        assert "local embedding" in result.output

        # The edited text must be what is actually stored and searched.
        from memdex.config import load_config
        from memdex.store import VectorStore

        store = VectorStore(load_config(demo_project))
        documents = store.memories.get(include=["documents"])["documents"]
        assert any("read replica in Frankfurt" in doc for doc in documents)
        assert "Database" in run(runner, "search", "read replica Frankfurt").output


